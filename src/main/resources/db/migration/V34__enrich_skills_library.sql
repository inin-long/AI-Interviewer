## 第二章：白板编程实战技巧

### 白板 vs IDE 的区别

| 维度 | IDE | 白板 |
|------|-----|------|
| 自动补全 | ✅ 有 | ❌ 没有 |
| 语法检查 | ✅ 实时 | ❌ 靠自己 |
| 运行测试 | ✅ 一键 | ❌ 脑内模拟 |
| 可见范围 | ✅ 滚动查看 | ❌ 空间有限 |
| 面试官感知 | 只看结果 | **全程可见你的思考** |

### 白板编码规范

#### 1. 书写工整
- 字不用好看，但必须**能辨认**
- 变量名要有意义（`i`, `j`, `k` 在简单循环里可以接受，但复杂逻辑要用 `left`, `right`, `pivot`）
- 适当缩进（白板上也要缩进！）

#### 2. 先写函数签名
```java
// ✅ 好
public List<List<Integer>> threeSum(int[] nums) {
    // ...
}

// ❌ 差（上来就写实现，面试官不知道你在干嘛）
```

#### 3. 留足修改空间
- 不要把白板写得密密麻麻
- 每行之间留一行空白（方便擦除修改）
- 重要变量写在右上角（常量/不变量）

#### 4. 主动标注复杂度
```java
// Time: O(n²)  ← 写出来！
// Space: O(1) 或 O(n) 取决于排序是否算在内
```

> 💡 **主动标注复杂度 = 主动展示你的分析能力**，面试官会觉得你很专业。

