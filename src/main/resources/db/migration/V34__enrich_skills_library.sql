## 第一章：Think Aloud —— 让面试官看到你的思考

### 什么是 Think Aloud？
就是在解题的过程中**把你脑子里的想法说出来**。这不是自言自语，而是让面试官实时跟踪你的思路，从而判断：
- 你的思路是否**清晰有条理**
- 你是否能**识别关键问题和 trade-off**
- 当遇到困难时你**如何调整方向**

### 实操模板

#### 拿到题目后的前 30 秒
> "好的，我来确认一下这道题的要求：
> 1. 输入是一个整数数组，可能有重复元素
> 2. 输出是所有唯一的三元组，和为零
> 3. 时间复杂度有要求吗？空间呢？
> 
> 我的初步想法是先排序，然后用双指针法。让我先举个例子验证一下……"

#### 为什么这样做有效？
- **确认需求**：避免理解偏差（做了半天发现题意搞错了是最惨的）
- **展示分析力**：你已经在考虑时间和空间复杂度了
- **争取缓冲时间**：说话的同时大脑在后台组织解法

### 口述的三个层次

| 层次 | 内容 | 何时使用 |
|------|------|----------|
| **L1 策略层** | "我打算用 XX 方法，因为…" | 刚开始分析时 |
| **L2 执行层** | "现在我把 left 指针右移，因为…" | 编码/画图时 |
| **L3 检查层** | "让我验证一下这个 case…" | 写完代码后 |

> ⚠️ **不需要每一句话都说出来**，关键是**关键的决策节点**要说清楚为什么。

