## 陷阱一："你最大的缺点是什么？"

### 出题意图
- 自我认知是否清晰（知道自己哪里弱）
- 是否诚实且有改进意识（不是假缺点也不是致命缺陷）
- 弱点是否影响岗位核心能力

### ❌ 减分回答
> "我最大的缺点就是太追求完美了/工作太拼命了。"
