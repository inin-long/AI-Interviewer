## 第二阶段：形象与准备（面试前 1 天）

### 着装原则

| 公司类型 | 推荐风格 | 避免 |
|-----------|----------|------|
| 金融/律所/咨询 | 正式西装、深色系、皮鞋 | 休闲装、鲜艳颜色 |
| 互联网大厂 | 商务休闲（衬衫/Polo + 西裤/西裙） | 过于随意（短裤/拖鞋） |
| 创业公司/AI 初创 | Smart Casual（干净整洁即可） | 不修边幅 |
| 技术/研发岗 | 衬衫/T恤（无图案）+ 干净长裤 | 有冒犯性文字/图案的衣服 |

> **黄金法则**：宁可**略正式**也绝不**太随意**。第一印象只有一次机会，7 秒形成且极难改变。

### 线上面试特别准备

#### 设备清单
- [ ] 摄像头位置：**眼睛平视高度**（笔记本垫高或外接摄像头）
- [ ] 光线：正面光源（面向窗户或在摄像头旁补灯），避免背光
- [ ] 网络：有线连接优先，手机开 hotspot 备用
- [ ] 音频：耳机（避免回声和环境噪音）
- [ ] 背景：简洁整洁（纯色墙面或虚化背景），**不要**出现床/杂物
- [ ] 桌面：只放纸笔和水杯，关掉所有无关应用通知
- [ ] 屏幕名：改成正式名字（不要叫"超级赛亚人"之类）

#### 测试流程
提前 30 分钟：
1. 打开会议软件测试音视频
