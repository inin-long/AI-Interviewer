## 陷阱四："你的薪资期望是多少？"

### 出题意图
- 你的市场定位是否准确
- 你是否了解自己的价值
- 双方期望是否在同一区间（快速筛选不匹配的候选人）

### ❌ 错误做法
- 直接报一个数字（可能偏高或偏低）
- 说"都可以"/"按公司标准"（显得没准备或不自信）
- 说一个离谱的高薪（显得不切实际）

### ✅ 谈薪策略

#### 第一步：反问（获取信息优势）
> "在回答这个问题之前，我想了解一下这个岗位的薪资结构和预算范围是怎样的？这样我可以给出一个更有参考价值的回答。"

#### 第二步：给范围（而非精确数字）
> "基于我对市场的了解和我的经验，我的期望年薪范围在 **[低值]–[高值]** 之间。当然，我也会综合考虑公司的整体福利、成长空间和工作内容来做最终决定。"

#### 范围设定原则
- 低值 = 你能接受的底线（略高于当前薪资 10–20%）
- 高值 = 你的理想值（市场 75 分位左右）
- 区间宽度 15–20%，给双方谈判空间

#### 薪资调研渠道
- Boss 直聘/拉勾的岗位薪资分布
- Offers Always Now / Levels.fyi（互联网行业）
- 同行朋友内部信息（最准）
- 前程薪酬报告

