- 职业规划和动机

#### 应届生 STAR 示范
> **S**：大三下学期，我和 3 位同学组队参加学校的黑客松比赛，要在 48 小时内开发一款校园生活服务 App。
>
> **T**：我负责后端 API 开发和数据库设计，需要在第一天晚上前完成核心接口，以便前端同学第二天能对接。
>
> **A**：这是我第一次独立设计 API，我先参考了 RESTful 最佳实践设计了 15 个接口，用 Swagger 写了文档。开发过程中遇到了跨域和数据一致性的问题，我通过查阅文档和请教学长解决了。为了让前端同学更方便，我还写了一个 Postman Collection。
>
> **R**：最终我们的项目获得了比赛二等奖。更重要的是，这次经历让我真正理解了前后端协作的痛点，也坚定了我想做后端开发的决心。

> 💡 **关键**：即使是学生项目，只要用 STAR 结构清晰地讲出来，一样能展现你的能力。

### 技术题：基础 > 花哨
