## 通用解题框架（7 步）

### Step 1: Clarify Requirements（需求澄清）⭐ 最重要！

**不要急着画图！** 先问清楚你在设计什么。

#### 必须澄清的问题
- **功能需求**：核心功能是什么？有哪些 edge case？
- **非功能需求**：
  - 规模：DAU / QPS / 数据量？
  - 一致性：强一致 vs 最终一致？
  - 可用性：几个 9？（99.9%? 99.99%?）
  - 延迟要求：实时？秒级？分钟级？
- **约束条件**：只能用一种语言？有预算限制？

#### 话术模板
> "在设计之前，我想确认几点：
> 1. 这是一个读写比例大概多少的系统？（我假设是读多写少）
> 2. 需要支持的并发用户量大概是多少？（我先按 100万 DAU 来设计）
> 3. 对于数据一致性，我们需要强一致还是最终一致可接受？
> 4. 需要考虑哪些功能特性？我先从 MVP 开始设计。"

### Step 2: Estimate Scale（规模估算）

快速估算关键指标，为后续技术选型提供依据：

| 指标 | 估算方法 | 示例 |
|------|---------|------|
| QPS | DAU × 每日活跃比 × 日均请求次数 | 100万 DAU × 10% × 5 = **5万 QPS** |
| 存储量 | 每条记录大小 × 日增量 × 保留时间 | 500B × 5万 × 365天 ≈ **8 TB/年** |
| 带宽 | QPS × 平均响应大小 | 5万 QPS × 2KB = **100 MB/s** |
| 内存 | 热数据集大小 | Top 10% 用户数据 ≈ **800 GB** |

### Step 3: High-Level Design（高层设计）

画出核心组件及其交互关系：

```
┌─────────┐    ┌─────────┐    ┌─────────┐
│ Client  │───▶│  Load   │───▶│ Web     │
│         │    │Balancer │    │ Server  │
└─────────┘    └────┬────┘    └────┬────┘
                    │              │
              ┌─────▼─────┐  ┌────▼────┐
              │  Cache    │  │   DB    │
              │ (Redis)   │  │(Primary)│
              └───────────┘  └───┬─────┘
                                  │
                           ┌──────▼──────┐
                           │ Replicas    │
                           └─────────────┘
```

说明每个组件的选择理由和 trade-off。

### Step 4: Database Schema（数据模型）

设计核心表结构：
- 表之间的关联关系
- 索引策略
- 分片/分区策略（如需要）

### Step 5: Deep Dive into Core Component（深入 1–2 个核心组件）

选面试官最感兴趣或最有挑战性的组件深入讨论：
- API 设计
- 数据结构选择
- 一致性/可用性保证
- 容错和恢复机制
- 监控和告警

### Step 6: Bottlenecks & Scaling（瓶颈与扩展）

分析当前设计的瓶颈：
- 单点故障在哪？
- 性能瓶颈在哪？
- 数据量增长后最先爆的是什么？

扩展方案：
- 水平扩展（增加实例）
- 垂直扩展（增强单机）
- 缓存层
- 异步处理
- CDN / Edge Computing

### Step 7: Follow-Up Discussion（追问讨论）

面试官一定会追问。常见方向：
- **规模扩大 10 倍**怎么办？
- **要求更强的一致性**怎么改？
- **多机房/跨国部署**怎么设计？
- **安全性**如何保证？
- **成本优化**怎么做？

