## 第三步：谈判心理学

### 1. 锚定效应（Anchoring）
**第一个说出的数字会成为"锚"**，影响后续所有讨论。
- 如果你先报价 → 报**略高于**你的目标值
- 如果对方先报价 → 无论多低，**不要立即拒绝或大笑**（保持镇定）

### 2. BATNA（Best Alternative to a Negotiated Agreement）
**你最好的替代选项**是什么？
- 有另一个 offer 在手 = 强大的 BATNA
- 没有其他选择 = 弱势地位
> 💡 **策略**：尽量让自己在谈判时有多个选择（即使还在流程中也行）

### 3. 让步策略（Reciprocity Concession）
**永远不要免费让步。** 每次让步都要换取对方的让步。
- "我可以接受这个薪资，但希望年终奖能从 2 个月提高到 3 个月。"
- "我可以接受这个 Base，但希望签字费能再高一些。"

### 4. 沉默的力量
提出你的期望后——**闭嘴等待对方回应**。很多人受不了沉默就会自己降价或补充条件。

