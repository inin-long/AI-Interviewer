## T — Task 任务（5–10%）

> 明确说出"你要解决的具体问题是什么"。

Task 不是团队的 KPI，而是**你个人承担的那一块**。要体现：
- 问题有多紧急/重要？
- 如果不解决会有什么后果？
- 这个任务是你主动认领的还是被指派的？（主动更好）

### 示例
> "我的任务是确保订单服务在大流量下不出现超时或数据不一致，SLA 要求 P99 响应时间控制在 200ms 以内。"

### 关键词提示
| 场景 | Task 表述模板 |
|------|--------------|
| 性能优化 | "将 X 的响应时间从 Y 降低到 Z" |
| Bug 修复 | "定位并解决导致 X 的根因问题" |
| 架构设计 | "为 Y 业务场景设计可扩展的 X 方案" |
| 团队协作 | "推动 X 个团队完成 Y 迁移，零停机" |

---

## A — Action 行动（50–60%）⭐ 核心

> 这是整个回答的灵魂。面试官最想听的就是**你具体做了什么**。

### 黄金法则
1. **多用"我"，少用"我们"**
   - "我们做了代码审查" → 不清楚你的贡献
   - "**我**主导设计了审查流程，**我**编写了 80% 的规则脚本" → 清晰

2. **说清楚"为什么"而不只是"做了什么"**
   - ❌ "用了 Redis 缓存"
   - ✅ "因为热点数据查询占了 70% 的数据库负载，所以我引入了 Redis 作为 L1 缓存，采用 Cache-Aside 模式"

3. **体现决策能力**
   - 列出你考虑过的方案（至少 2–3 个）
   - 说明为什么选了最终方案（trade-off 分析）
   - 如果有更好的方案现在回想，也可以诚实地说

4. **量化动作**
   - "优化了代码" → 太空
   - "**重构了 12 个核心 Service 类，将循环依赖从 47 处减少到 3 处**" → 有画面感

### Action 的结构建议
按时间顺序组织，每一步遵循 **"发现→分析→行动→验证"** 的闭环：

> "首先我发现订单创建接口的慢查询集中在库存扣减步骤（发现）。通过分析 Explain 执行计划，确认是库存表锁竞争导致（分析）。我引入了 Redis 预扣减 + 异步补偿的双层方案（行动）。压测显示 P99 从 380ms 降到 95ms（验证）。"

