## 第四章：写完代码后的自查清单

每次写完代码，**主动**（不要等面试官提醒）做以下检查：

### 功能正确性
- [ ] 跑一遍例子（用题目给的 example）
- [ ] 边界情况：空输入、单个元素、全部相同、极大输入
- [ ] 特殊情况：null/None、负数、溢出

### 代码质量
- [ ] 变量命名是否清晰
- [ ] 有没有重复代码可以抽取
- [ ] 边界条件是否统一处理

### 复杂度分析
- [ ] Time Complexity 是多少？能否优化？
- [ ] Space Complexity 是多少？能否降低？

### 主动演示
> "代码写完了。让我跑一下题目给的例子验证一下……[口述执行过程]……结果符合预期。另外我注意到如果输入数组长度小于 3 的情况需要特殊处理，让我加上这个 guard clause……"
> 
> "Time Complexity 是 O(n²)，主要来自排序和双指针扫描。Space 是 O(1)（不算排序的空间开销）。如果要进一步优化，可以考虑……"

> 🔥 **这种主动自查的行为是高分候选人和普通候选人的最大区别。**

