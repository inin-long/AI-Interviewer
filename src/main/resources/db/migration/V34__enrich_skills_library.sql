## 5 个经典题目速览

### 1. URL Shortener（短链接服务）
**核心挑战**：ID 生成（全局唯一 + 短）、重定向性能（高 QPS 读）

**关键设计点**：
- **ID 生成**：Base62 编码 / Snowflake ID / 预生成池
- **存储**：Redis（热门）+ DB（持久化）两级
- **重定向**：301（永久，利于 SEO）vs 302（临时，便于统计）
- **自定义短链**：冲突检测 + ACID 事务

### 2. Distributed Instant Messaging（聊天/IM）
**核心挑战**：实时性 + 消息有序 + 离线存储 + 多端同步

**关键设计点**：
- **协议**：WebSocket 长连接 + 心跳保活
- **消息路由**：在线状态服务 + 连接映射表
- **消息存储**：写扩散（收件箱模型）vs 读扩散（发件箱模型）
- **顺序保证**：Logical Clock / Vector Clock
- **群聊**：Message Queue Fan-out

### 3. News Feed（信息流/朋友圈）
**核心挑战**：个性化 + 低延迟 + 高并发写入

**关键设计点**：
- **Fan-Out-on-Write**（推模式）：发文时推送到所有粉丝的 Inbox
- **Fan-Out-on-Read**（拉模式）：读取时聚合关注者的 posts
- **混合策略**：大 V 用推模式，普通人用拉模式
- **Ranking**：热度分数（点赞/评论/时间的衰减函数）
- **缓存**：Hot feeds 缓存 + 冷热分离

### 4. Web Crawler（爬虫系统）
**核心挑战**：规模 + 去重 + 礼貌爬取 + 内容更新检测

**关键设计点**：
- **URL Frontier**：Bloom Filter 去重 + Priority Queue 排序
- **DNS 解析缓存**：避免重复 DNS 查询
- ** politeness**：robots.txt + Rate Limiting per domain
- **存储**：Document Store（ES）+ Link Graph（图数据库）
- **分布式**：Master-Worker 架构 + Task Queue

### 5. Search Autocomplete（搜索联想）
**核心挑战**：低延迟（< 100ms）+ 实时更新 + 多语言

**关键设计点**：
- **数据源**：Query Log + Document Titles + Trending Topics
- **索引**：Trie Tree（前缀树）+ Top-K 缓存
- **排序**：Frequency + Recency + Personalization 加权
- **更新**：Near-Realtime batch update + Hot Query 实时插入
- **客户端**：预加载 + 本地缓存 + 防抖

