## 六种压力场景的标准应对

### 场景 1：连续追问到底

**面试官**："你这个方案的复杂度是多少？""能优化吗？""还有什么办法？""就这？"

**❌ 错误反应**：
- 逐渐加快语速（越说越慌）
- 最后说"我不知道"然后沉默
- 开始编造答案

**✅ 标准应对**：
> "目前这个方案的时间和空间复杂度分别是 O(n log n) 和 O(n)。如果要进一步优化，我想到的方向有 [A 和 B]。不过说实话，在有限时间内我暂时没有想到更优的解法。如果这是一个实际工作中遇到的性能瓶颈，我会去查阅相关论文和社区实践，看看业界有哪些成熟的方案。"

**关键点**：
- ✅ 诚实承认局限（比瞎编强）
- ✅ 展示思考方向（说明你有潜力）
- ✅ 表达学习的意愿（展示成长型思维）

---

### 场景 2：质疑你的经历真实性

**面试官**："你说的这个项目，感觉不像是一个人能完成的吧？"

**❌ 错误反应**：
- "就是我自己做的啊！"（愤怒/防御）
- "呃……其实是团队一起的……"（被吓到改口）
- "你不信就算了"（对抗）

**✅ 标准应对**：
> "这是一个很好的问题。确实，这个项目涉及的范围比较广，我一个人不可能覆盖所有方面。具体来说，我主要负责的是 [你的核心模块]，大概占整体工作量的 [X]%。其他部分由我的同事 [简要提一下分工] 负责。如果你想了解更多细节，我可以展开讲我负责这部分的技术决策和实现。"

**关键点**：
- ✅ 先认同（"这是个好问题"）
- ✅ 明确界定你的贡献范围（诚实 + 具体）
- ✅ 主动邀请深入（"我可以展开讲……" = 自信的表现）

---

### 场景 3：沉默冷场

**面试官**：（你回答完后一言不发，盯着你看 10 秒）

**❌ 错误反应**：
- 开始补充更多内容（越补越乱）
- "我说完了吗？还有什么问题？"（暴露焦虑）
- 低头看桌面/手指

**✅ 标准应对**：
1. **保持微笑和眼神接触**
2. **在心里数到 5**
3. 如果对方还不说话，主动打破沉默：
> "以上就是我对这个问题的看法。不知道我的回答是否解答了您的疑问？或者您想让我从其他角度再展开？"

**原理**：沉默通常是面试官在**观察你的反应**或者在**记笔记**。你不慌，你就赢了。

---

### 场景 4：不合理要求

**面试官**："如果今天下班前你要把这个功能上线，你做不做？"

**❌ 错误反应**：
- "没问题！"（盲目答应 = 不专业）
- "这怎么可能！"（直接拒绝 = 不合作）

**✅ 标准应对**（三段式）：
> "我理解业务的紧迫性。如果真的遇到这种情况，我会这样做：
>
> 首先，快速评估最小可行方案——哪些功能是 must-have，哪些可以 nice-to-have later。
> 其次，和产品和测试同学对齐一个最小上线范围和回滚预案。
