## 第四阶段：面试进行中

### 进门/接入的那一刻

**线下**：
1. 敲门（即使门开着）后听到"请进"再进入
2. 微笑 + 目光接触 + 点头致意
3. 等对方示意后再坐下（不要自己拉椅子就坐）
4. 把物品整齐放在椅子旁/脚边，不要堆在桌面上

**线上**：
1. 开启摄像头后先微笑点头
2. 先开口问候（"您好，我是 XXX，很高兴见到您"）
3. 确认对方能听清你的声音

### 肢体语言速查

| 动作 | 传递的信息 | 建议 |
|------|------------|------|
| 身体微微前倾 | 关注、感兴趣 | ✅ 保持 |
| 目光接触 60–70% 时间 | 自信、真诚 | ✅ 自然注视眉眼三角区 |
| 手势辅助表达 | 思路清晰、有热情 | ✅ 适度使用 |
| 双臂交叉抱胸 | 防御、封闭 | ❌ 避免 |
| 频繁摸脸/头发 | 紧张、不确定 | ❌ 控制 |
| 看手表/手机 | 不耐烦、不尊重 | ❌ 绝对禁止 |
| 坐姿歪斜/靠椅背 | 松懈、不认真 | ❌ 保持直立 |

### 回答问题的礼仪细节
- **不要打断面试官**（即使你知道答案）
- **回答前可以停顿 2–3 秒**思考（显得沉稳，比抢答强）
- **不知道就说不知道**，但要加上"我的理解是…如果是这种情况我会…"展现思维过程
- **语速适中**：太快=紧张/背稿子；太慢=反应迟缓
- **音量**：比平时说话大声 10%（显得自信）

