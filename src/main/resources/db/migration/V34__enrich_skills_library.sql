## R — Result 结果（15–20%）

> 用数据和反馈收尾，让故事有"落地点"。

### 必须包含的内容
1. **量化指标**（最重要的！）
   - 性能提升了多少倍？
   - 节省了多少成本/人力？
   - 影响了多少用户/业务量？
   - Bug 率降低了多少？

2. **业务影响**
   - 这件事对产品/用户有什么实质帮助？
   - 是否被其他团队复用？

3. **个人成长**（可选但加分）
   - 学到了什么方法论？
   - 后续如何避免类似问题？

### 示例
> "上线后双十一当天订单服务 P99 控制在 87ms，零故障支撑了 32000 QPS 峰值。这个缓存方案后来推广到了支付和营销两个模块。我也因此总结了一套「高并发场景下的缓存设计 Checklist」分享给了全组。"

### 如果结果是负面的怎么办？
不是所有故事都有完美结局。如果项目失败了，**诚实地分析原因**反而能展示你的成熟度：

> "虽然最终因为业务方向调整该项目被搁置，但我从中学会了：第一，技术选型要提前做 PoC 验证；第二，跨团队协作需要建立明确的接口契约。这两个教训在我后来的项目中都避免了类似问题。"

