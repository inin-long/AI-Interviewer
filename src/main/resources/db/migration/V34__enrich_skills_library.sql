## 陷阱二："你为什么离开上一家公司？"

### 出题意图
- 你离职的真实原因（是否有隐性问题）
- 你是否会说前公司坏话（反映人品和职业素养）
- 你的职业动机是否正向（是"向往什么"还是"逃避什么"）

### ❌ 绝对禁区
- 吐槽前公司/上级/同事（哪怕他们真的很差）
