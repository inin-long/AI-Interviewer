年终奖: 2个月 × 35,000 = 70,000（保底）
签字费: 50,000（一次性）
股票: RSU 4年vesting，每年25股，当前$180/股 ≈ 18,000/年
房补: 4,000/月 × 12 = 48,000
─────────────────────────────
年度总现金: ~641,000
+ 股票（4年总计）: ~72,000
≈ 年度总包: ~650,000+
```

> 💡 **关键**：不要只看月薪 Base。同样的月薪，不同的年终奖政策+股票+补贴，年度总包可以差 30% 以上。

