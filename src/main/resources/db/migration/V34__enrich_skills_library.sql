> "在设计之前，我想确认几点：
> 1. 这是一个读多还是写多的系统？
> 2. 需要支持的用户规模大概是多少 DAU？
> 3. 对一致性/可用性的要求哪个更高？
> 4. 需要考虑哪些功能特性？（先做 MVP 再扩展）"

### 第二步：Estimate Scale（估算规模）
- QPS / TPS 估算
- 存储量估算
- 带宽估算

### 第三步：High-Level Design（高层设计）
- 画 Core Components
- 说明各组件职责和数据流
- 选择关键技术方案并说明 trade-off

### 第四步：Deep Dive（深入 1–2 个核心组件）
- 选面试官最感兴趣的点展开
- 详细说明数据结构、API 设计、容错机制

### 第五步：Bottleneck & Scalability（瓶颈与扩展）
- 当前设计的瓶颈在哪？
- 如何水平扩展？
- 如何处理故障？

### 第六步：Follow-up Discussion
- 面试官可能会追问："如果规模扩大 10 倍怎么办？"
- 保持开放态度，讨论多种方案的优劣

