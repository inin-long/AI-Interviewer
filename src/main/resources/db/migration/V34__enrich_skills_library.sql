## 声音控制（非语言的听觉维度）

### 语速
| 情况 | 建议语速 |
|------|---------|
| 默认 | 每分钟 150–180 字（中文）|
| 讲复杂技术概念 | 放慢 20%（给听众消化时间）|
| 讲激动人心的成果 | 可以稍快（传递能量）|
| 回答压力问题时 | **刻意放慢**（显得沉稳）|

### 音量
- 比平时对话**大声 10–15%**（传递自信）
- 但不要喊（显得有攻击性）
- 如果发现自己声音越来越小 → 立即调整（可能是紧张导致的）

### 停顿（最有力的非语言工具）
- **回答前停顿 2–3 秒** = 思考（显得沉稳）
- **要点之间停顿 1 秒** = 强调（让对方消化）
- **说完一个完整观点后停顿 2 秒** = 给对方提问/反应的机会
- **被问到难题时停顿 5 秒** = 比脱口而出一个烂答案强一万倍

### 语调变化
- 单调的语调 = 无趣 = 面试官走神
- **有起伏的语调** = 有感染力 = 面试官被吸引
- 在关键词上**加重音量**或**提高语调**来强调

