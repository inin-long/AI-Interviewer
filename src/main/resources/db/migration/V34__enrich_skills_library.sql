## S — Situation 情境（10–15%）

> 用两三句话交代背景，像一个电影开场镜头。

### 要点
- **什么项目/产品？** 一句话说明业务背景
- **团队规模和你的角色？** 让人知道你在什么位置
- **遇到了什么约束或挑战？** 时间紧、技术债、人员不足都可以

### 示例（好）
> "去年双十一大促期间，我在一个 5 人后端团队负责订单服务。系统设计承载 QPS 5000，但实际峰值预期达到 20000+，且距离大促只有三周时间。"

### 示例（不好）
> "当时我们在做一个电商项目，挺忙的。" —— 太模糊，没有任何信息量。

### 常见错误
- ❌ 花太多篇幅讲公司历史（面试官不关心）
- ❌ 堆砌无关的技术名词（显得像背书）
- ✅ **聚焦到和你直接相关的约束条件**

