## 眼神接触的艺术

### 多少时间？
- **60–70%** 的时间保持眼神接触（最佳区间）
- 低于 50% = 逃避/不自信/可能在撒谎
- 高于 80% = 可能被视为侵略性或诡异

### 看哪里？（三角区法则）
```
     ▽ 眉毛之间
    /   \
   ◉ ◉ ◉  ← 看这个倒三角区域
    \ /
     △ 鼻尖
```
- **不要**一直盯着一颗瞳孔看（会让人不舒服）
- 在眉毛之间、双眼、鼻尖之间**自然移动**

### 什么时候该移开视线？
- 思考时（看向侧上方或侧下方 = 在回忆/组织语言）
- 回忆具体数据时（短暂移开是正常的）
- 笑的时候（自然会眯眼）

### 多人面试时的眼神分配
- 主要回答提问者，但**定期扫视其他面试官**（每 10–15 秒一次）
- 当另一位面试官插话时，**立刻转移目光到对方**
- 结束回答时，目光回到**最初的提问者**

