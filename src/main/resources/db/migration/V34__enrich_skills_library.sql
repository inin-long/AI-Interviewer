## 第一步：读懂 Offer 的完整构成

一个 Offer 不只是一个数字，它的组成部分包括：

| 组成部分 | 说明 | 评估要点 |
|---------|------|----------|
| **月薪 Base** | 月固定工资 | 最核心的部分，通常是 12–13 薪 |
| **年终奖** | 1–6 个月不等 | 问清楚：保底还是有条件？过去 3 年实际发放比例？ |
| **签字费/入职奖金** | 一次性 | 通常用于弥补你放弃的原公司奖金/股票 |
| **股票/期权** | RSU / ISO | **注意**： vesting schedule、行权价格、当前估值、稀释风险 |
| **补贴** | 房交/餐补/交通/通讯 | 问清楚税前还是税后、每月固定还是凭票报销 |
| **保险公积金** |五险一金 | 缴纳基数和比例（最高 vs 最低差距很大） |
| **假期** | 年假/病假/带薪假 | 年假天数、是否可累积 |
| **远程办公/弹性** | WFA / Flex time | 隐形福利，生活质量影响巨大 |
| **培训/教育** | 培训预算/会议/认证 | 职业发展的隐性投资 |

### 总报酬计算器（示例）
```
