## 陷阱三："你遇到过最大的失败是什么？"

### 出题意图
- 你是否敢于面对失败（而不是回避或粉饰）
- 你能否从失败中学习和复盘
- 你在压力下是否保持理性

### ❌ 减分回答
> "我从来没失败过。"（不现实）
> "有一次项目延期了，但那是产品经理需求老变的锅。"（甩锅）
> "期末考试没考好。"（和工作无关）

### ✅ STAR 格式回答（重点放在 R 的反思上）
> **S**：去年我主导了一次数据库迁移方案，选择了分库分表方案。
>
> **T**：目标是将单表 5 亿数据的查询性能提升 3 倍以上。
>
> **A**：我低估了数据迁移过程中的一致性保障难度，上线后出现了约 0.03% 的数据不一致问题。发现问题后，我立即带队进行了全量数据校验和修复，连续三天处理到凌晨两点。
>
> **R**：虽然最终修复了全部数据，没有造成业务损失，但这对我来说是一次重要的教训。事后我总结了三点改进：第一，大规模数据变更必须有完整的回滚方案；第二，灰度发布策略应该更保守（我们从 10% 开始改为 1%）；第三，数据一致性校验应该纳入自动化 CI 流水线。这三条规则后来成为了团队的技术规范。

### 关键点：**一定要说到你学到了什么具体的东西**。失败不可怕，可怕的是同一个坑掉两次。

