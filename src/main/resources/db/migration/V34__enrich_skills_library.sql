## 为什么你需要 STAR？

在一场 45 分钟的技术面试中，行为问题往往占 **20–30 分钟**。面试官不是在闲聊——他们在用这些题目判断：

- 你是否**真的做过**你简历上写的事
- 你面对压力时**如何思考和行动**
- 你的**沟通逻辑**是否清晰
- 你能否从经历中**学习和成长**

泛泛而谈的回答（"我们团队做了个重构"）会让面试官觉得你只是**旁观者**。STAR 法则是让你从旁观者变成**主角**的最有效工具。

