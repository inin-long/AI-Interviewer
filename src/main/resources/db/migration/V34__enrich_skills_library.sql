## 第五阶段：面试结束

### 得体的收尾
1. **感谢对方的时间**（真诚地，不是说套话）
2. **询问下一步流程和时间线**（"请问大概什么时候会有反馈？"）
3. **如有准备好的问题，这时候提问 1–2 个**（展示你的积极性和思考深度）
4. **起身/关闭视频时再次道谢**

### 可以问的好问题（按优先级排序）
1. "这个岗位目前团队面临的最大挑战是什么？"
2. "您认为在这个岗位上做得优秀的人，具备什么样的特质？"
3. "接下来 6–12 个月，团队的重点方向是什么？"
4. "团队的工程文化和协作方式是怎样的？"

> ❌ **不建议问的问题**（第一轮）：
> - 薪资福利细节（留到 HR 轮或 offer 阶段）
> - "我要加班吗？"（负面暗示）
> - 能不能在家办公（除非对方主动提）

