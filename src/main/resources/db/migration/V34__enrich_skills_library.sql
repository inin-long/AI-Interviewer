## 第三章：处理"卡壳"的正确姿势

### 卡壳时的心理建设
**卡壳是正常的！** 面试官出的题本来就是有一定难度的。关键是你卡住之后的**反应方式**。

### ❌ 错误反应
- 沉默超过 30 秒（面试官会尴尬，你也会越来越慌）
- 说"这道题我不会"然后放弃（直接淘汰）
- 乱写一通（不如不写）

### ✅ 正确反应（C-A-S 框架）

#### C — Communicate（说出来）
> "我现在想到的是暴力枚举的方法，时间复杂度是 O(n³)，但感觉应该有更优解。让我想想能不能用 Hash Map 来优化……"

#### A — Analyze（分析瓶颈）
> "目前的瓶颈在于去重操作耗时太高。如果我先排序，是不是可以用双指针跳过重复元素？"

#### S — Simplify or Switch（简化或换方向）
- **简化**：先用简化版的输入/输出来解，然后再扩展
- **换方向**：如果一条路走不通，主动说"我换个思路试试"
- **求助**（高级技巧）：可以问面试官要 Hint

> "我现在的思路好像走进了死胡同。能不能给我一个小提示？或者我应该从哪个方向重新思考？"

> 适当求助**不是减分项**，反而是成熟的体现。说明你知道自己的边界在哪里，并且善于利用资源。

