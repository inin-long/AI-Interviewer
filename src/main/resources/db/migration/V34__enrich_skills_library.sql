## 核心心法：ACE 反应模型

### A — Acknowledge（接纳）
> 承认现状，不否认不防御。

**内心独白**："好吧，他/她在给我施压。这是正常的面试环节，不是人身攻击。"

### C — Compose（镇定）
> 控制情绪和肢体语言。

**生理调节**：
- 深呼吸 2 次（激活副交感神经）
- 放慢语速（平时语速的 0.8x）
- 保持眼神接触（不要躲闪）
- 身体姿态开放（不要交叉手臂）

### E — Engage（应对）
> 用专业的方式回应，不卑不亢。

