## 第三阶段：到达与等候（面试前 15 分钟）

### 到达时机
- **线下**：提前 **10–15 分钟** 到达前台/大厅
  - 太早（>30min）= 给对方造成压力
  - 准时或迟到 = 印象分直接扣减
- **线上**：提前 **5–10 分钟** 进入会议室等待
  - 不要最后一秒才点进链接
  - 如果面试官还没来，耐心等，不要频繁发消息催

### 等候区的行为（很多人在这里丢分）
- ✅ 坐姿端正，看准备的资料或公司介绍
- ✅ 对前台/接待人员微笑点头示意
- ❌ 大声打电话、刷抖音、抖腿
- ❌ 和朋友发消息吐槽"又要面试了好烦"
- ❌ 吃东西或喝气味重的饮料

> 💡 **小秘密**：很多公司会请前台或接待人员对候选人的等候行为打分。别以为没人在意。

