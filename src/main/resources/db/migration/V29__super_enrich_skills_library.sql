## 第一轮：HR 初面（Gate Keeper）

### HR 面的真实目的
HR 面不是闲聊——它是**第一道筛选关卡**。HR 在评估：
- 你的基本条件是否满足硬性要求（学历/经验/薪资预期）
- 你的沟通表达能力是否达标
- 你的稳定性如何（跳槽频率/离职原因/职业规划）
- 你的性格和文化是否大致匹配
- 有没有任何明显的 red flags

### HR 面的常见问题与应对

| 问题 | HR 想知道什么 | 应对策略 |
|------|-------------|---------|
| "请做个自我介绍" | 表达能力 + 逻辑性 + 核心亮点 | 1 分钟版本，突出与岗位匹配的经验 |
| "为什么离开上一家公司" | 稳定性 + 职业素养 | 正面表述，不吐槽（详见陷阱题文章）|
| "你的薪资期望" | 预算匹配度 | 给范围不给精确数（详见薪资谈判文章）|
| "你的职业规划" | 稳定性 + 成长意愿 | 展示中长期在公司发展的意愿 |
| "你还有什么问题问我吗" | 兴趣度 + 思考深度 | 问 1-2 个关于团队/文化/成长的问题 |
| "你最快什么时候能到岗" | 可用性 | 给出合理的交接期（通常 2-4 周）|
| "你在上一家的薪资" | 定价参考 | 可以给一个范围，不必报精确数字 |

### HR 面的加分项
- ✅ 回答问题时**结构清晰**（第一/第二/第三）
- ✅ **态度积极但不谄媚**
- ✅ 对公司**做过基本调研**
- ✅ 薪资期望**合理且有弹性**
- ✅ 表现出**稳定性**（不频繁跳槽）

### HR 面的减分项
- ❌ 对公司**一无所知**
- ❌ **抱怨**前公司/前领导
- ❌ 薪资期望**远超预算**且不 flexible
- ❌ **模棱两可**的态度
- ❌ **迟到**或**着装不当**

