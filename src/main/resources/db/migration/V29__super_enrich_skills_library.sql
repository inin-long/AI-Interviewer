> "我有时会在细节上花过多时间，导致整体进度受影响。比如上次做方案评审，我对 PPT 格式调整了四版，差点延误会议。之后我开始给自己设定''细节时间上限''——初版只关注内容和逻辑，格式最后批量处理。这个方法节省了约 30% 的方案准备时间。"

