## 反向提问的黄金法则

### 法则一：不要问"百度一下就知道的"
❌ "你们公司主要是做什么的？"（致命伤）
❌ "你们有多少员工？"（官网写着呢）
✅ "我注意到贵公司最近在 XX 领域有新的布局，能否分享一下背后的战略考虑？"（展示了调研）

### 法则二：第一轮不要问薪资福利
❌ "薪资范围是多少？""有加班费吗？"
✅ 这些问题留给 HR 轮或 offer 阶段

### 法则三：每个问题都要有"为什么"
