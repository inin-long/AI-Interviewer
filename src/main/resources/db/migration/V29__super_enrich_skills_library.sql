## 互联网大厂面试攻略

### 流程特点
1. **简历筛选严格**：ATS 系统自动过滤 + HR 初筛
2. **笔试/在线测评**：大部分大厂有笔试环节（算法题 + 行测 + 性格测试）
3. **技术面 2–3 轮**：每轮侧重不同（基础 → 进阶 → 系统/架构）
4. **交叉面试（Cross Interview）**：其他团队的面试官来面你（防作弊）
5. **HR 面**：薪酬期望 + 文化匹配 + 背调准备
6. **委员会评审（Hiring Committee）**：所有面试官集体讨论决定

### 大厂面试的核心考点
| 轮次 | 主要内容 | 准备重点 |
|------|---------|---------|
| **一面（基础）** | 语言基础 + 数据库 + 网络 + OS | 《Java并发编程》《高性能MySQL》等技术基础书 |
| **二面（进阶）** | 项目深挖 + 中等难度算法 + 设计模式 | LeetCode Medium 200+；项目每个细节都能讲清楚 |
| **三面/四面（高级）**| 系统设计 + 架构思维 + 技术视野 | 《Designing Data-Intensive Applications》; 经典系统设计题 |
| **HR面** | 薪资/文化/稳定性 | 了解公司的价值观和近期新闻 |

### 大厂专属技巧
- **算法题必须 Think Aloud**：大厂面试官非常看重你的解题思路而不只是答案
- **项目经历要有"争议点"**：面试官喜欢问你"如果重新做你会怎么改"——准备好答案
- **了解大厂的最新技术动向**：比如阿里的云原生布局、字节的基础设施建设等

