>
> **R**：项目虽然按时上线了，但砍掉的功能影响了用户体验，后续又花了 2 周补回来。
>
> **🆕 Reflection**：这次失败让我学到三点深刻的教训：第一，技术方案的验证必须有充分的时间和 data-driven 的 evidence，不能凭感觉；第二，对于高风险模块需要有 fallback 方案；第三，当发现进度风险时要**尽早 raise flag** 而不是硬扛。此后我建立了个人的「项目风险管理 checklist」，在后续 3 个项目中再也没有出现过类似问题。

### 案例 2：团队冲突（协作类）
> **S**：在一次跨部门项目中，我和前端负责人对于 API 的错误码设计产生了分歧。
>
> **T**：我们需要在一周内统一错误码规范，否则两边的联调无法推进。
>
> **A**：我当时过于坚持己见，花了两天时间去"证明"我的方案更好，而不是去倾听对方的诉求。结果导致气氛僵化，进度停滞。
>
> **R**：最终还是通过 Tech Lead 的介入才解决了分歧，但浪费了一周时间。
>
