## 第三章：线上面试的表现技巧

### 镜头感：看着摄像头而不是屏幕
这是线上面试最大的挑战——你需要**对着摄像头说话**而不是看着屏幕上的面试官的脸。

**训练方法**：
1. 把面试官的视频窗口拖到你**摄像头附近**（尽量靠近）
2. 或者**直接最小化视频窗口**，只保留音频——强迫自己看摄像头
3. 在摄像头旁边贴一个小便签：**"看我！看我！"**

> 看着摄像头 = 和面试官有眼神接触（在对方的感知里）
> 看着屏幕 = 你在看别处（面试官会觉得你在走神）

### 延迟应对
线上面试有 200ms–2s 的延迟，会导致：
- 你们同时开口说话（重叠）
- 对方的反应比你预期的慢
- 出现尴尬的沉默间隙

**应对策略**：
- **说完一句后多等 1 秒**再继续
- 如果出现重叠，礼貌地让对方先说："抱歉，您请。"
- 不要因为延迟而加快语速（会更糟）

### 手势放大效应
摄像头会**放大你的手势**。线下合适的手势力度在线上可能显得过于激烈。
- **手势幅度减小 30%**
- **手保持在胸部以上、肩膀以下**
- **不要频繁挥手**（画面晃动 = 晕眩感）

### 声音投射
线上音频会丢失一些"温暖感"。你需要：
- **音量比平时大 10–15%**
- **发音更清晰**（不要吞音）
- **语速放慢 10%**（补偿延迟导致的听觉负担）

