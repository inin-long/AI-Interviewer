## 第一章：硬件准备清单

### 摄像头（最重要的硬件！）

| 要求 | 说明 |
|------|------|
| **位置** | 眼睛平视高度（笔记本垫高 15cm 或使用笔记本支架）|
| **清洁** | 用眼镜布擦拭镜头（指纹会让画面模糊）|
| **角度** | 稍微俯拍 5–10°（显脸小且自然）|
| **距离** | 脸部占画面 1/3–1/2，头顶上方留一点空间 |
| **画质** | 至少 720p，推荐 1080p |

> 💡 **测试方法**：打开前置摄像头的预览，想象你在和一个坐在对面的人交谈。画面看起来自然吗？

### 麦克风
- **首选**：有线入耳式耳机（音质最好 + 隔绝环境噪音）
- **备选**：蓝牙耳机（延迟可能有问题，测试后再用）
- **避免**：电脑自带麦克风（收音差 + 回声严重）
- **禁忌**：使用音箱外放（对方会听到回声）

### 灯光（被严重低估的因素！）
| 光源 | 效果 | 建议 |
|------|------|------|
| **正面主光源**（窗户/环形灯）| ✅ 最佳 | 面部均匀照亮，眼神有光 |
| **顶部光源**（吸顶灯）| ⚠️ 一般 | 眼窝和鼻子下方有阴影 |
| **背面光源**（窗户在你背后）| ❌ 灾难 | 你的脸是黑的，像审讯现场 |
| **侧光** | ⚠️ 可以接受 | 有立体感但要补另一边 |

> **最佳方案**：面向窗户坐（自然光）+ 台灯补光（消除面部阴影）。如果晚上面试，买一个便宜的环形灯（50 元以内）放在摄像头后方。

