### 维度八：道德与价值观（Questions 19-20）

**Q19: "你有没有遇到过需要做出艰难的道德/伦理选择的时刻？"**
- **意图**：价值观 + 诚信 + 判断力
- **推荐故事类型**：数据隐私/用户利益 vs 商业利益 / 发现 bug 是否上报 / 看到不正当行为
- **STAR 重点**：A（如何权衡 + 最终决定 + 为什么这么做）+ R（后果 + 反思）

**Q20: "你有没有过''做正确的事但不受欢迎"的经历？"**
- **意图**：勇气 + 原则性 + 影响力
- **推荐故事类型**：提出反对意见 / 坚持正确的技术方案 / 保护用户/团队利益
- **STAR 重点**：S（压力来自哪里）+ A（如何坚持 + 如何沟通）+ R（最终结果 + 影响）

