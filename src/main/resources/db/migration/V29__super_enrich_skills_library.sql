### 版本二：1分钟标准版（最常用）

> **结构公式**：基本信息(10秒) + 核心能力与亮点(35秒) + 与岗位的匹配(15秒)

#### 通用模板
> **[基本信息 10秒]**
> 我叫[姓名]，[学校/学历]，目前有[X]年[领域]工作经验。
