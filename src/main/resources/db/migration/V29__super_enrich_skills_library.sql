## 第一模块：基本信息与个人情况（10 题）

### Q1: 请简单介绍一下你自己
**意图**：考察信息提炼能力 + 第一印象建立
**思路**：核心标签 + 量化成果 + 匹配度（详见《自我介绍完全攻略》一文）
**一句话示范**："5年后端经验，专注高并发架构，曾将核心接口P99从500ms降到50ms。"

### Q2: 你的优点是什么？
**意图**：自我认知 + 是否匹配岗位
**思路**：选 2–3 个与岗位强相关的优点 + 每个配一个简短实例
**示范**："第一是执行力强，比如上次紧急项目我连续一周加班提前交付；第二是学习能力强，两周内从零掌握了K8s并上线了服务。"

### Q3: 你的缺点是什么？
**意图**：诚实程度 + 改进意识
**思路**：真实非致命短板 + 已采取的改进措施 + 已见成效
**示范**："公开演讲是我的弱项，这半年我加入了Toastmasters俱乐部，最近一次Tech Talk控制在18分钟内完成。"

### Q4: 用三个词描述你自己
**意图**：自我定位的精准度
**思路**：选 3 个互补的、正面的、与岗位相关的词 + 每个词用一句话解释
**示范**："驱动型——我喜欢主动推动事情发生；数据型——我做决策依赖数据而非直觉；协作型——我善于在多元团队中找到共同目标。"

### Q5: 你的朋友/同事怎么评价你？
**意图**：侧面了解你的口碑 + 人际关系质量
**思路**：借他人之口说出你想强调的优点
**示范**："同事们通常说我是个靠谱的人——交待给我的事情一定会有反馈；朋友们觉得我比较乐于助人，经常找我帮忙看方案。"

### Q6: 你最大的成就感是什么？
**意图**：价值观判断 + 成就是否可信
**思路**：用 STAR 选一个与岗位相关的最大成就
**示范**：略（参考 STAR 文章中的完整范例）

### Q7: 你遇到过最大的失败/挫折？
**意图**：抗压能力 + 学习反思能力
**思路**：真实失败 + 深度复盘 + 具体改进措施（重点落在 R 的反思）
**示范**：略（参考陷阱题文章中的完整范例）

### Q8: 你的兴趣爱好是什么？
**意图**： personality fit + 工作生活平衡观
**思路**：说 1–2 个真实的 + 如果能关联到工作更好
**示范**："我喜欢跑步和读书。跑步帮我保持精力充沛，读书习惯让我能持续学习新技术。最近在读《系统设计面试》这本书。"

### Q9: 你有什么想问我们的吗？（反问）
**意图**：积极性 + 思考深度
**思路**：问体现思考和调研的高质量问题（详见《反向提问的艺术》一文）
**示范**："这个岗位在未来半年的核心挑战是什么？"

### Q10: 你还有什么要补充的吗？（收尾题）
**意图**：给你最后展示自己的机会
**思路**：补充 1–2 个前面没机会说但很重要的亮点
**示范**："我想补充一点：除了技术能力之外，我也很注重文档沉淀和知识分享，在上一家公司我维护的技术博客团队内部阅读量最高。"

