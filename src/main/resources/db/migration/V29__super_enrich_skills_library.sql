## 第四章：特殊情况处理

### 断网了怎么办？

**预防措施**：
- 手机上装好同一个会议 App 并登录同一账号
- 提前告知面试官你的备用联系方式（手机号）

**断网时的操作**：
1. **不要慌**（30 秒内的短暂中断很正常）
2. **立即尝试重连**
3. 如果 1 分钟无法恢复，**用手机拨打面试官电话**道歉并说明情况
4. 重连后简短道歉："不好意思，刚才网络出了点问题。我们刚刚聊到……"

### 家里有干扰（宠物/小孩/室友）

**最佳做法**：
- **提前打招呼**："我家可能有只猫会突然出现，请见谅 😅"
- **关门**（物理隔绝）
- **告知家人/室友**面试时间段（最重要！）
- 如果还是出现了——**微笑着简单处理**，不要过度反应（反而显得可爱/真实）

### 需要共享屏幕时
1. **提前打开**你要展示的内容
2. **只共享需要的窗口**（不要共享整个桌面）
3. **关闭所有通知**
4. 共享结束后**立即停止共享**

