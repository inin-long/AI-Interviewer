## 如何选择合适的失败案例？

### 好的失败案例的标准

| 标准 | 说明 |
|------|------|
| **真实** | 一定是真实发生的（面试官会追问细节）|
| **可控** | 不是"公司倒闭了我失业了"这种不可抗力 |
| **有反思** | 你能清楚说出学到了什么 |
| **已改进** | 你采取了具体行动来防止再次发生 |
| **不致命** | 不要选和应聘岗位核心能力直接相关的致命失误（如会计说"我曾经挪用公款"）|

### 推荐的失败案例来源
1. **项目延期/失败**：时间预估不足、需求变更、技术选型错误
2. **技术决策失误**：选择了不合适的技术方案、低估了复杂度
3. **人际/沟通失误**：和同事/上级产生误解、沟通不及时
4. **个人能力短板**：在某项技能上不足导致的问题（现在已经改善了）
5. **创新尝试未果**：尝试了一个新方法但效果不如预期（体现创新精神）

### 绝对不要说的"失败"
- ❌ "我从来没有失败过"（不现实）
- ❌ "我最大的失败是太努力工作了"（变相自夸）
- ❌ "高考没考好/考研失败了"（太遥远且和工作无关）
- ❌ "前公司倒闭了"（不可抗力，看不出你的问题）
- ❌ "和前男友/女友分手了"（过于私人）

