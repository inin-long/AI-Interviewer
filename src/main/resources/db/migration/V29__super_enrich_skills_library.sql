## 第二模块：职业规划与求职动机（15 题）

### Q11: 为什么选择我们公司/这个岗位？
**意图**：调研深度 + 动机真实性
**思路**：行业趋势 + 公司具体亮点 + 个人匹配（三层递进）
**示范**：略（参考陷阱题文章第 7 条）

### Q12: 你对我们公司了解多少？
**意图**：是否做过功课
**思路**：说 3 个具体的、网上不容易搜到的信息
**示范**："我知道贵公司最近完成了B轮融资，投资方是XX；去年发布了XX开源项目；在XX行业报告中市场份额排名前三。"

### Q13: 你未来 3–5 年的职业规划是什么？
**意图**：稳定性 + 成长性 + 目标匹配度
**思路**：短期融入 + 中期深化 + 长期发展（三段式）
**示范**：略（参考陷阱题文章第 6 条）

### Q14: 为什么离开上一家公司？
**意图**：离职原因 + 职业素养
**思路**：肯定过去 → 聚焦向往 → 不吐槽前公司
**示范**：略（参考陷阱题文章第 2 条）

### Q15: 你为什么想换工作/转行？
**意图**：职业决策理性度
**思路**：内在驱动力 + 外部契机 + 清晰目标
**示范**："我在上一家公司已经做到了Team Lead，但我希望能在AI应用领域做更深入的探索。贵公司在这个方向的投入和愿景正是我下一步想要聚焦的方向。"

### Q16: 如果我们和你同时录用另一个人，为什么要选你？
**意图**：差异化竞争力
**思路**：独特组合 + 不可替代性 + 即时价值
**示范**："我的差异化在于：既有深厚的技术功底（X年经验），又有产品思维（独立负责过从0到1的项目），还能快速融入团队（在上一家公司1周内就成为核心开发者）。这种''技术+产品+协作''的组合可能比较少见。"

### Q17: 你期望的薪资是多少？
**意图**：市场定位 + 谈判成熟度
**思路**：反问 → 给范围 → 综合考量（参考薪资谈判文章）
**示范**：略（参考薪资谈判文章）

### Q18: 你能接受加班吗？
**意图**：工作态度 + 文化匹配
**思路**：正面回应 + 边界意识
**示范**："我认为在关键项目节点加班是必要的，也是职业素养的体现。但我更倾向于通过合理的时间管理和优先级排序来避免常态化加班。"

### Q19: 你能接受出差/外派吗？
**意图**：灵活性 + 家庭因素
**思路**：视具体情况给出合理范围
**示范**："短期出差（每周2-3天）完全可以接受；长期外派需要视具体时长和地点来评估，我会和家人商量后给答复。"

### Q20: 你更看重薪资还是成长空间？
**意图**：价值观判断
**思路**：平衡回答，不偏废任一方
**示范**："两者都很重要。短期内我更看重成长空间——因为我相信能力的提升最终会反映在长期回报上。但我也期望公司能提供具有市场竞争力的薪酬，这样我才能安心投入工作。"

### Q21: 你对这个岗位的理解是什么？
**意图**：岗位认知准确度
**思路**：职责 + 挑战 + 所需能力
**示范**："据我的理解，这个岗位的核心职责包括：一是XX（日常执行），二是XX（跨部门协调），三是XX（战略支持）。最大的挑战可能在于XX，需要具备XX能力和XX能力。"

### Q22: 你什么时候可以到岗？
**意图**：可用性 + 对现任雇主的尊重
**思路**：合理的交接期（通常2-4周）
**示范**："按照正常的离职流程，大概需要3周时间完成交接。如果公司有特殊需求，我也可以尝试加快进度。"

### Q23: 你还在面试其他公司吗？
**意图**：市场需求度 + 诚意
**思路**：诚实但不透露具体信息
**示范**："是的，我也在和其他几家公司沟通。但坦率地说，贵公司是我最优先的选择，因为……"

