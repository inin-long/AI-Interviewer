## 让面试官记住你的 6 个技巧

### 1. 开场制造"认知钩子"
不要以"您好，我叫XXX，今年XX岁"开头——太普通了。
> ✅ "我是一个把代码当艺术品来雕琢的后端工程师。"（让人好奇）
> ✅ "我曾经在一个项目中，用一行配置改动为公司节省了每年 200 万的服务器成本。"（数字钩子）

### 2. 使用"标签化"自我描述
给自己贴 2–3 个精准的职业标签：
> "如果用三个词形容我的职业形象，那就是：**系统思维者、问题终结者、技术布道者**。"

### 3. 在介绍中埋下"追问诱饵"
故意留一个有趣的细节不展开：
> "关于那个项目的细节，如果您感兴趣我可以展开讲，这里先跳过。"（90% 的面试官会追问）

### 4. 关联面试官/公司的具体信息
> "我看到您之前在 XX 大会上做过关于 XX 的分享，其中提到的 XX 观点让我很有共鸣。"（做了功课 + 建立连接）

### 5. 用数据而非形容词
> ❌ "我有很强的学习能力"
> ✅ "我在 2 周内从零掌握了 Kubernetes 并在生产环境中部署了首个服务网格"

### 6. 以行动号召结尾
> "以上就是我的简要背景。不知道您希望我先从哪个方面展开聊？"

