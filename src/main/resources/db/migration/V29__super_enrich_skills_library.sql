## 缺点篇：如何说得安全又真实？

### 安全缺口的三个特征

| 特征 | 说明 | 示例 |
|------|------|------|
| **非致命** | 不影响岗位核心能力 | 后端工程师说"公开演讲能力待提升" ✅；前端工程师说"我不太会写 CSS" ❌ |
| **可改善** | 已经在采取行动改进 | "我这半年在参加 Toastmasters" ✅；"我就是这样的性格改不了" ❌ |
| **有边界** | 缺点的影响范围有限 | "我在公众场合容易紧张"（影响范围有限）✅；"我和人打交道有困难"（影响范围太大）❌ |

### 10 个安全的缺点及回答模板

#### 1. 公共演讲 / 表达能力
> "我在公共演讲方面还有提升空间。以前做 Team Sharing 时容易紧张和超时。这半年来我刻意练习了两件事：一是每次分享前写逐字稿并排练三次；二是参加了公司的演讲俱乐部。最近一次 Tech Talk 我控制在 18 分钟内完成，Q&A 也更从容了。"

