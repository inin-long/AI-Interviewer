## 5 类职位的差异化写法

| 职位 | 重点突出 | 关键词 | 示例句式 |
|------|---------|--------|---------|
| **技术岗** | 项目复杂度 + 技术深度 + 解决难题 | 架构/性能/可靠性 | "主导过XX系统的设计，处理过XX规模的并发" |
| **产品岗** | 用户洞察 + 数据驱动 + 结果导向 | 增长/转化/体验 | "从0到1打造了XX功能，带来了XX%的业务增长" |
| **运营岗** | 执行力 + 创意 + 数据敏感 | 获客/留存/活跃 | "策划过XX活动，实现了XX万曝光/转化" |
| **管理岗** | 团队建设 + 战略思维 + 影响力 | 带领/推动/变革 | "管理过XX人的团队，推动了XX转型" |
| **校招** | 学习潜力 + 实习/项目 + 成绩/奖项 | 快速学习/实习/竞赛 | "在校期间完成了XX项目，获得了XX奖项" |

