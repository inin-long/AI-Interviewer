- "我做了功课"（调研类问题）
- "我有深度思考"（战略类问题）
- "我很在意这个岗位"（细节类问题）
- "我能带来价值"（贡献类问题）

### 法则四：控制在 2–3 个问题
太多 = 抓不住重点；太少 = 缺乏兴趣

