## 第二轮：业务/技术面（Core Evaluation）

### 业务面的真实目的
这是**最重要的一轮**。面试官通常是你的 future manager 或 team member，他们在评估：
- 你能不能**干得了这个活**
- 你的**技术/专业能力**是否达标
- 你的**思维方式**是否和团队匹配
- 你是否**好相处**（以后要天天共事的）

### 业务面的结构（通常 45–60 分钟）

| 阶段 | 时长 | 内容 | 你的策略 |
|------|------|------|---------|
| **暖场** | 3-5 min | 自我介绍 + 简历过一遍 | 控制 2-3 分钟，留出更多时间给后面的技术问题 |
| **项目深挖** | 15-20 min | 挑 1-2 个项目详细问 | 用 STAR 法则 + 准备好追问答案 |
| **技术/专业问题** | 15-20 min | 算法/系统设计/专业问题 | Think Aloud + 主动自查 |
| **行为/情景问题** | 5-10 min | 团队合作/冲突/压力 | 调用 STAR 故事库 |
| **反向提问** | 3-5 min | 你问面试官问题 | 准备 2-3 个高质量问题 |

### 业务面的高分策略

#### 1. 项目深挖环节——最容易出彩的地方
面试官一定会挑你的一个项目深入问。常见的追问链路：
```
"介绍一下这个项目"
    ↓
"你在其中的角色是什么？具体负责哪些模块？"
    ↓
"遇到的最大困难是什么？你怎么解决的？"
    ↓
"如果重新做，你会怎么做？"
    ↓
"这个技术方案有什么 trade-off？"
    ↓
"你在其中学到了什么？"
```
**每一层都要准备好答案！**

#### 2. 技术问题的答题节奏
- **前 30 秒**：Clarify requirements（确认需求）
- **中间 10-15 分钟**：Solution + Implementation（解题 + 实现）
- **最后 2-3 分钟**：Follow-up + Complexity analysis（优化 + 复杂度分析）

#### 3. 不知道答案时的应对
> "这个问题我暂时没有很好的思路。不过基于我对 [相关领域] 的理解，我会从以下几个角度来分析……如果您能给一点提示的话，我可以试着展开。"

