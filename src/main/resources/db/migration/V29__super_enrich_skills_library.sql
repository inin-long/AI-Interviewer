## 外资企业面试攻略

### 流程特点
1. **Phone Screen**（电话初筛）：30 分钟，基础行为题 + 简单 coding
2. **Onsite/Virtual Onsite**：半天到一天，4–5 轮连续进行
3. **Bar Raiser**：专门有一轮由非直属部门的资深员工来做"门槛把关人"
4. **Behavioral Questions 是重中之重**：使用 BEI（Behavioral Event Interview）方法

### 外企面试的核心差异

#### BEI 方法论（Behavioral Event Interview）
外企（尤其是 Google/Amazon/Microsoft）大量使用 BEI 方法，其特点是：
- **只关注过去的具体行为**：不问"你会怎样"，只问"你曾经怎样"
- **追问极其深入**：一个行为问题可能追问 10–15 分钟
- **LP 导向**：围绕公司的 Leadership Principles 展开（如 Amazon 的 16 条 LP）

#### Amazon Leadership Principles 示例
> 面试官可能会说："请分享一个例子，说明你体现了 Customer Obsession（客户至上）这一原则。"
>
> 回答时必须：
> 1. 先复述原则含义（表明你理解）
> 2. 给出一个具体的行为案例（STAR）
> 3. 明确指出你的哪个行动对应哪条 LP

### 外企专属技巧
- **每个回答都要有 Structure**：First/Second/Third 或 Situation/Action/Result
- **不要夸大**：外企对诚信要求极高，背景调查很严
- **准备英文回答**：即使全程中文，也可能被问到英文技术术语或英文自我介绍
- **展示 Global Mindset**：跨国协作经验、英语能力、文化包容性

