## 三套时间版本的话术模板

### 版本一：30秒电梯版（适用于快速筛选/群面开场）

> **结构公式**：我是谁 + 核心标签 + 最亮眼的一个成果 + 为什么来这里

#### 技术岗示例
> 您好，我是张三，一名有 **5 年后端开发经验**的工程师，专注于高并发系统设计。我曾在上一家公司主导过日活千万级平台的核心链路重构，将系统可用性从 99.5% 提升至 **99.99%**。我对贵公司在 AI 应用基础设施方向的投入非常关注，相信我的分布式架构经验能为团队带来直接价值。

#### 产品岗示例
> 您好，我是李四，**4 年互联网产品经验**，擅长从 0 到 1 的产品孵化。我曾独立负责一款教育 App 的从需求调研到上线的全过程，上线 6 个月用户突破 **50 万**，次日留存率达到 **42%**。贵司在职业教育赛道的深耕让我很兴奋，希望能用我的产品方法论为团队创造价值。

