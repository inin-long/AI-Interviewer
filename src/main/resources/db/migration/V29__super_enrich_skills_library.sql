## 自我介绍的常见错误

| 错误 | 为什么减分 |
|------|-----------|
| 背简历原文（逐字念）| 显得没思考、没准备 |
| 讲家庭情况/出生地/爱好 | 和工作无关，浪费时间 |
| 超过 2 分钟 | 面试官会走神或不耐烦 |
| 太谦虚/太夸张 | 不自信或不可信 |
| 没有"所以呢"（没有落脚点）| 信息堆砌，没有结论 |
| 说完就低头等下一个问题 | 失去互动机会 |

