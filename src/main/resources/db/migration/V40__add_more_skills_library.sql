✅ "不是一时冲动，而是经过深思熟虑。我在原岗位已经达到了 XX 阶段，发现 XX 领域更符合我的长期兴趣和优势。"

### 2. "你觉得自己最大的劣势是什么？"
✅ "行业专用知识需要补充，但我已经制定了学习计划，并且我的可迁移能力可以让我快速上手。"

### 3. "你的职业规划是什么？"
✅ "短期快速补齐行业知识，中期在 XX 方向形成专业深度，长期成为能独当一面的人。"

### 4. "如果工作后发现自己不适合怎么办？"
✅ "我在选择前已经做了充分调研，包括 XX。如果真的遇到挑战，我会主动沟通、调整方法，而不是轻易放弃。"

### 5. "你期望的薪资会不会太高/太低？"
✅ "我了解转行初期可能需要一定调整，更看重成长空间。同时我也希望薪资能反映我的能力和市场价值。"

### 6. "你为什么离开上一家公司？"
✅ "聚焦未来向往，不要吐槽过去。"

---

